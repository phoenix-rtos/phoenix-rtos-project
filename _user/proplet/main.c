#define SEC_TO_US(s) (s * 1000000)

static struct option opts[] = {
	{ "host", required_argument, 0, 'a' },
	{ "port", required_argument, 0, 'p' },
	{ "secure", no_argument, 0, 's' },
	{ "no-verify", no_argument, 0, 't' },
	{ "ca-bundle", required_argument, 0, 'c' },
	{ "client-key", required_argument, 0, 'l' },
	{ "client-certificate", required_argument, 0, 'k' },
	{ "verbose", no_argument, 0, 'v' },
	{ NULL, 0, 0, 0 },
};


void print_help(char *cmdline)
{
	/* clang-format off */
	fprintf(stderr, "usage: %s [options]\n"
					"\t-a, --host <address>\n"
					"\t\tMQTT broker hostname or address\n"
					"\t-p, --port <port>\n"
					"\t\tMQTT broker port\n"
					"\t-s, --secure\n"
					"\t\tUse TLS for broker transport\n"
					"\t-c, --ca-bundle\n"
					"\t\tPath to a root certificate bundle, used for mTLS if enabled serverside\n"
					"\t-l, --client-certificate\n"
					"\t\tPath to a client certificate, used for mTLS if enabled serverside\n"
					"\t-k, --client-key\n"
					"\t\tPath to a client certificate key, used for mTLS if enabled serverside\n"
					"\t-t, --no-verify\n"
					"\t\tDisable server certificate verification\n"
					"\t-v, --verbose\n"
					"\t\tBe louder!\n"
					"\n"
					"Additionally, some parameters are passed exclusively by environmental variables:\n"
					"\tPROPLET_CLIENT_ID\n"
					"\t\tUUID for the Proplet generated by Propeller, used as client identifier and username in MQTT communication, must be set\n"
					"\tPROPLET_CLIENT_KEY\n"
					"\t\tSecret UUID generated by Propeller for Proplet, used as password in MQTT communication, must be set\n"
					"\tPROPLET_DOMAIN_ID\n"
					"\t\tMagistrala domain UUID for the domain that Propeller operates in, used in MQTT topics, must be set\n"
					"\tPROPLET_CHANNEL_ID\n"
					"\t\tMagistrala channel UUID for the channel that Propeller operates in, used in MQTT topics, must be set\n"
					"\tPROPLET_TAGS\n"
					"\t\tTags for this proplet, used in metadata, optional\n"
					"\tPROPLET_DESCRIPTION\n"
					"\t\tNode description, used in metadata, optional\n"
					"\tPROPLET_LOCATION\n"
					"\t\tNode location, used in metadata, optional\n", cmdline);
	/* clang-format on */
}


static void process_loop(void)
{
	uint32_t counter = 0;
	MQTTStatus_t status;

	for (;;) {
		status = plt_mqtt_process();
		/* MQTTRecvFailed likely signals a connection timeout, ignore to not spam syslog */
		if (status != MQTTSuccess && status != MQTTRecvFailed) {
			fail("MQTT processing failed with MQTT status: %s", MQTT_Status_strerror(status));
		}

		plt_taskman_sample_metrics();

		if (counter % SEC_TO_US(4) == 0) {
			status = plt_mqtt_publish_alive();
			if (status != MQTTSuccess) {
				fail("Publishing alive message failed with MQTT status: %s", MQTT_Status_strerror(status));
			}

			plt_taskman_publish_task_metrics();

			if (counter % SEC_TO_US(30) == 0) {
				status = plt_mqtt_publish_system_metrics();
				if (status != MQTTSuccess) {
					fail("Publishing metrics message message failed with MQTT status: %s", MQTT_Status_strerror(status));
				}
			}
		}

		usleep(PROPLET_MQTT_PROCESS_INTERVAL_USEC);
		counter += PROPLET_MQTT_PROCESS_INTERVAL_USEC;
		counter %= SEC_TO_US(30);
	}
}


int main(int argc, char *argv[])
{
	int opt, idx = 0;
	bool secure = false, verify = true;
	char *host = NULL, *port = "1883", *cabundle = NULL, *clientkey = NULL, *clientcert = NULL;
	MQTTStatus_t status;
	struct proplet_context ctx;

	assert(argc > 0);

	if (argc == 1) {
		print_help(*argv);
		return EXIT_SUCCESS;
	}

	while ((opt = getopt_long(argc, argv, "p:a:c:l:k:", opts, &idx)) != -1) {
		switch (opt) {
			case 's':
				secure = !secure;
				break;
			case 'a':
				host = optarg;
				break;
			case 'p':
				port = optarg;
				break;
			case 'c':
				cabundle = optarg;
				break;
			case 'l':
				clientkey = optarg;
				break;
			case 'k':
				clientcert = optarg;
				break;
			case 't':
				verify = !verify;
				break;
			case 'v':
				PLT_LOGGING_VERBOSE = !PLT_LOGGING_VERBOSE;
				break;
			case 'h':
			case '?':
				print_help(*argv);
				return EXIT_SUCCESS;
				break;
			default:
				break;
		}
	}

	ctx.proplet_id = getenv("PROPLET_CLIENT_ID");
	ctx.client_key = getenv("PROPLET_CLIENT_KEY");
	ctx.domain_id = getenv("PROPLET_DOMAIN_ID");
	ctx.channel_id = getenv("PROPLET_CHANNEL_ID");
	ctx.description = getenv("PROPLET_DESCRIPTION");
	ctx.tags = getenv("PROPLET_TAGS");
	ctx.location = getenv("PROPLET_LOCATION");

	if ((host == NULL) || (ctx.proplet_id == NULL) || (ctx.domain_id == NULL) || (ctx.client_key == NULL) || (ctx.channel_id == NULL)) {
		print_help(*argv);
		return EXIT_FAILURE;
	}

	openlog("proplet", LOG_CONS, LOG_DAEMON);

	plt_taskman_init();

	status = plt_mqtt_init(&ctx);
	if (status != 0) {
		fail("Failed to initialize MQTT: %s", MQTT_Status_strerror(status));
	}

	status = plt_mqtt_connect(host, port, secure, verify, cabundle, clientcert, clientkey);
	if (status != MQTTSuccess) {
		fail("Failed to connect: %s", MQTT_Status_strerror(status));
	}

	status = plt_mqtt_subscribe();
	if (status != MQTTSuccess) {
		fail("Failed to subscribe: %s", MQTT_Status_strerror(status));
	}

	status = plt_mqtt_publish_discovery();
	if (status != MQTTSuccess) {
		fail("Failed to publish discovery packet: %s", MQTT_Status_strerror(status));
	}

	log_info("Successfully connected to %s", host);

	process_loop();

	/* @TODO: signal handler and cleanup function */
	plt_mqtt_destroy();
	closelog();

	return EXIT_SUCCESS;
}
